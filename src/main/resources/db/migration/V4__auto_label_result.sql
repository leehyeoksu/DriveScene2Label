-- Draft: Spring owns job lifecycle and transactional ingestion; GT stays separate.
CREATE TABLE auto_label_job (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dataset_id BIGINT NOT NULL REFERENCES dataset(id),
 request_key TEXT NOT NULL,
 retry_of_job_id BIGINT,
 target_type TEXT NOT NULL CHECK (target_type IN ('SCENE','SAMPLE')),
 requested_targets JSONB NOT NULL CHECK (jsonb_typeof(requested_targets)='array' AND jsonb_array_length(requested_targets)>0),
 model_name TEXT NOT NULL DEFAULT 'VESPA',
 model_version TEXT NOT NULL,
 config_name TEXT NOT NULL,
 model_config JSONB NOT NULL CHECK (jsonb_typeof(model_config)='object'),
 mapping_name TEXT NOT NULL CHECK (mapping_name IN ('1class','3class','8class')),
 class_names JSONB NOT NULL CHECK (jsonb_typeof(class_names)='array' AND jsonb_array_length(class_names)>0),
 coordinate_frame TEXT NOT NULL DEFAULT 'WORLD' CHECK (coordinate_frame='WORLD'),
 score_type TEXT NOT NULL DEFAULT 'VESPA_CONSTANT' CHECK (score_type IN ('VESPA_CONSTANT','MODEL_CONFIDENCE')),
 status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','RUNNING','COMPLETED','FAILED')),
 execution_token UUID,
 result_checksum TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 started_at TIMESTAMPTZ,
 completed_at TIMESTAMPTZ,
 failure_reason TEXT,
 UNIQUE(dataset_id,request_key),
 UNIQUE(dataset_id,id),
 FOREIGN KEY(dataset_id,retry_of_job_id) REFERENCES auto_label_job(dataset_id,id),
 CHECK (retry_of_job_id IS NULL OR retry_of_job_id<>id),
 CHECK (started_at IS NULL OR started_at>=created_at),
 CHECK (completed_at IS NULL OR completed_at>=COALESCE(started_at,created_at)),
 CHECK (
  (status='PENDING' AND started_at IS NULL AND completed_at IS NULL AND failure_reason IS NULL AND execution_token IS NULL AND result_checksum IS NULL)
  OR (status='RUNNING' AND started_at IS NOT NULL AND completed_at IS NULL AND failure_reason IS NULL AND execution_token IS NOT NULL AND result_checksum IS NULL)
  OR (status='COMPLETED' AND started_at IS NOT NULL AND completed_at IS NOT NULL AND failure_reason IS NULL AND execution_token IS NOT NULL AND result_checksum IS NOT NULL)
  OR (status='FAILED' AND completed_at IS NOT NULL AND failure_reason IS NOT NULL AND length(trim(failure_reason))>0 AND result_checksum IS NULL)
 )
);

-- Expand requested scenes into exact sample targets in Spring before dispatch.
CREATE TABLE auto_label_job_sample (
 job_id BIGINT NOT NULL,
 dataset_id BIGINT NOT NULL,
 sample_token VARCHAR(64) NOT NULL,
 result_received_at TIMESTAMPTZ,
 PRIMARY KEY(job_id,sample_token),
 UNIQUE(dataset_id,job_id,sample_token),
 FOREIGN KEY(dataset_id,job_id) REFERENCES auto_label_job(dataset_id,id) ON DELETE CASCADE,
 FOREIGN KEY(dataset_id,sample_token) REFERENCES sample(dataset_id,token)
);

CREATE TABLE predicted_annotation (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id BIGINT NOT NULL,
 dataset_id BIGINT NOT NULL,
 sample_token VARCHAR(64) NOT NULL,
 box_index INTEGER NOT NULL CHECK (box_index>=0),
 detection_name TEXT NOT NULL CHECK (detection_name IN ('vehicle','car','truck','bus','trailer','construction_vehicle','pedestrian','motorcycle','bicycle')),
 center_x DOUBLE PRECISION NOT NULL,
 center_y DOUBLE PRECISION NOT NULL,
 center_z DOUBLE PRECISION NOT NULL,
 size_w DOUBLE PRECISION NOT NULL CHECK (size_w>0 AND size_w<'Infinity'::double precision),
 size_l DOUBLE PRECISION NOT NULL CHECK (size_l>0 AND size_l<'Infinity'::double precision),
 size_h DOUBLE PRECISION NOT NULL CHECK (size_h>0 AND size_h<'Infinity'::double precision),
 rotation_w DOUBLE PRECISION NOT NULL,
 rotation_x DOUBLE PRECISION NOT NULL,
 rotation_y DOUBLE PRECISION NOT NULL,
 rotation_z DOUBLE PRECISION NOT NULL,
 velocity_x DOUBLE PRECISION NOT NULL,
 velocity_y DOUBLE PRECISION NOT NULL,
 detection_score DOUBLE PRECISION NOT NULL CHECK (detection_score>=0 AND detection_score<=1),
 attribute_name TEXT NOT NULL DEFAULT '',
 raw_payload JSONB NOT NULL CHECK (jsonb_typeof(raw_payload)='object'),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(job_id,sample_token,box_index),
 FOREIGN KEY(dataset_id,job_id,sample_token) REFERENCES auto_label_job_sample(dataset_id,job_id,sample_token) ON DELETE CASCADE,
 CHECK (center_x>'-Infinity'::double precision AND center_x<'Infinity'::double precision),
 CHECK (center_y>'-Infinity'::double precision AND center_y<'Infinity'::double precision),
 CHECK (center_z>'-Infinity'::double precision AND center_z<'Infinity'::double precision),
 CHECK (velocity_x>'-Infinity'::double precision AND velocity_x<'Infinity'::double precision),
 CHECK (velocity_y>'-Infinity'::double precision AND velocity_y<'Infinity'::double precision),
 CHECK (abs(rotation_w*rotation_w+rotation_x*rotation_x+rotation_y*rotation_y+rotation_z*rotation_z-1.0)<=0.001)
);

CREATE TABLE auto_label_artifact (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id BIGINT NOT NULL REFERENCES auto_label_job(id) ON DELETE CASCADE,
 artifact_type TEXT NOT NULL CHECK (artifact_type IN ('FINAL_JSON','RERUN','OTHER')),
 storage_key TEXT NOT NULL,
 relative_path TEXT NOT NULL,
 checksum TEXT,
 content_type TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(job_id,storage_key,relative_path)
);

CREATE INDEX idx_auto_label_job_status ON auto_label_job(status,created_at);
CREATE INDEX idx_auto_label_job_dataset_time ON auto_label_job(dataset_id,created_at);
CREATE INDEX idx_auto_label_job_retry ON auto_label_job(dataset_id,retry_of_job_id) WHERE retry_of_job_id IS NOT NULL;
CREATE INDEX idx_auto_label_job_sample ON auto_label_job_sample(dataset_id,sample_token,job_id);
CREATE INDEX idx_predicted_sample_class ON predicted_annotation(dataset_id,sample_token,detection_name);
CREATE INDEX idx_auto_label_artifact_job_type ON auto_label_artifact(job_id,artifact_type);

COMMENT ON COLUMN predicted_annotation.detection_score IS 'VESPA exports constant 1.0; interpret using job.score_type, not as calibrated confidence.';
COMMENT ON COLUMN predicted_annotation.box_index IS 'Zero-based JSON array index within one job/sample, not a track ID.';
COMMENT ON COLUMN auto_label_job.execution_token IS 'Spring dispatch UUID; reject stale callbacks with another token.';
COMMENT ON COLUMN auto_label_job_sample.result_received_at IS 'NULL: unprocessed. Non-NULL and no boxes: processed empty result.';
