CREATE TABLE dataset (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, version TEXT NOT NULL,
 storage_key TEXT NOT NULL, root_relative_path TEXT NOT NULL, source_checksum TEXT NOT NULL,
 UNIQUE(name, version)
);

CREATE TABLE capture_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dataset_id BIGINT NOT NULL REFERENCES dataset(id),
 token VARCHAR(64) NOT NULL,
 logfile TEXT NOT NULL,
 location TEXT NOT NULL,
 date_captured TEXT NOT NULL,
 vehicle TEXT NOT NULL,
 raw_payload JSONB NOT NULL,
 UNIQUE(dataset_id, token)
);

CREATE TABLE map_asset (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dataset_id BIGINT NOT NULL REFERENCES dataset(id),
 token VARCHAR(64) NOT NULL,
 relative_path TEXT NOT NULL,
 category TEXT NOT NULL,
 raw_payload JSONB NOT NULL,
 UNIQUE(dataset_id, token)
);

CREATE TABLE scene (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dataset_id BIGINT NOT NULL REFERENCES dataset(id),
 token VARCHAR(64) NOT NULL,
 log_token TEXT NOT NULL,
 name TEXT NOT NULL,
 description TEXT NOT NULL,
