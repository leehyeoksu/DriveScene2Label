CREATE INDEX idx_sample_data_frame ON sample_data(dataset_id, sample_token, is_key_frame);
CREATE INDEX idx_gt_sample ON gt_annotation(dataset_id, sample_token);
ALTER TABLE sample_data ADD CHECK (width >= 0 AND height >= 0);
ALTER TABLE gt_annotation ADD CHECK (size_w > 0 AND size_l > 0 AND size_h > 0);
