CREATE TABLE map_log (
 dataset_id BIGINT NOT NULL, map_token VARCHAR(64) NOT NULL, log_token VARCHAR(64) NOT NULL,
 PRIMARY KEY(dataset_id, map_token, log_token),
 FOREIGN KEY(dataset_id, map_token) REFERENCES map_asset(dataset_id, token),
 FOREIGN KEY(dataset_id, log_token) REFERENCES capture_log(dataset_id, token)
);
CREATE TABLE annotation_attribute (
 dataset_id BIGINT NOT NULL, annotation_token VARCHAR(64) NOT NULL, attribute_token VARCHAR(64) NOT NULL,
 PRIMARY KEY(dataset_id, annotation_token, attribute_token),
 FOREIGN KEY(dataset_id, annotation_token) REFERENCES gt_annotation(dataset_id, token),
 FOREIGN KEY(dataset_id, attribute_token) REFERENCES attribute(dataset_id, token)
);
CREATE INDEX idx_scene_dataset ON scene(dataset_id, name);
